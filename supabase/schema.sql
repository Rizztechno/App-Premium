-- ---------- 1. TABEL ----------
create table if not exists public.products (
  id             bigint generated by default as identity primary key,
  slug           text not null,
  name           text not null,
  category       text not null,
  category_label text not null default '',
  badge          text,
  badge_color    text,
  image_url      text,
  description    text,
  sort_order     int  not null default 1,
  is_visible     boolean not null default true,
  is_ready       boolean not null default true,
  variants       jsonb not null default '[]'::jsonb,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  order_code     text not null,
  buyer_name     text not null,
  buyer_wa       text not null,
  buyer_email    text,
  payment_method text,
  note           text,
  items          jsonb not null default '[]'::jsonb,
  total          int  not null default 0,
  status         text not null default 'pending',
  created_at     timestamptz not null default now()
);

-- Jika tabel lama kamu belum punya kolom tertentu, tambahkan:
alter table public.products add column if not exists updated_at timestamptz not null default now();
alter table public.orders   add column if not exists created_at timestamptz not null default now();

create unique index if not exists products_slug_key      on public.products (slug);
create unique index if not exists orders_order_code_key  on public.orders (order_code);
create index        if not exists orders_buyer_wa_idx    on public.orders (buyer_wa, created_at desc);

-- Daftar akun admin (hanya diisi manual lewat SQL Editor, tidak bisa diakses API)
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- ---------- 2. CONSTRAINT VALIDASI (NOT VALID = data lama tidak dicek, data baru wajib lolos) ----------
alter table public.products drop constraint if exists products_slug_chk;
alter table public.products add  constraint products_slug_chk
  check (slug ~ '^[a-z0-9-]{1,40}$') not valid;

alter table public.products drop constraint if exists products_category_chk;
alter table public.products add  constraint products_category_chk
  check (category in ('editing','streaming','music')) not valid;

alter table public.products drop constraint if exists products_badge_color_chk;
alter table public.products add  constraint products_badge_color_chk
  check (badge_color is null or badge_color in (
    'bg-cyan-500/20 text-cyan-300 border-cyan-500/30',
    'bg-emerald-500/20 text-emerald-300 border-emerald-500/30',
    'bg-amber-500/20 text-amber-300 border-amber-500/30',
    'bg-rose-500/20 text-rose-300 border-rose-500/30',
    'bg-red-500/20 text-red-300 border-red-500/30',
    'bg-blue-500/20 text-blue-300 border-blue-500/30',
    'bg-pink-500/20 text-pink-300 border-pink-500/30',
    'bg-white/15 text-white border-white/25',
    'bg-green-500/20 text-green-300 border-green-500/30',
    'bg-teal-500/20 text-teal-300 border-teal-500/30'
  )) not valid;

alter table public.products drop constraint if exists products_image_url_chk;
alter table public.products add  constraint products_image_url_chk
  check (image_url is null or (image_url ~ '^https://' and length(image_url) <= 500)) not valid;

alter table public.products drop constraint if exists products_text_len_chk;
alter table public.products add  constraint products_text_len_chk
  check (length(name) <= 80 and length(category_label) <= 60
         and length(coalesce(badge,'')) <= 30 and length(coalesce(description,'')) <= 400) not valid;

alter table public.products drop constraint if exists products_variants_chk;
alter table public.products add  constraint products_variants_chk
  check (jsonb_typeof(variants) = 'array' and jsonb_array_length(variants) <= 12) not valid;

alter table public.orders drop constraint if exists orders_status_chk;
alter table public.orders add  constraint orders_status_chk
  check (status in ('pending','approved','refunded')) not valid;

-- Validasi isi varian di sisi database (id, label, harga bulat 0..10.000.000)
create or replace function public.validate_variants() returns trigger
language plpgsql set search_path = public, pg_temp as $$
declare e jsonb;
begin
  for e in select * from jsonb_array_elements(new.variants) loop
    if jsonb_typeof(e) <> 'object'
       or jsonb_typeof(e->'id') <> 'string' or char_length(e->>'id') not between 1 and 60
       or jsonb_typeof(e->'label') <> 'string' or char_length(e->>'label') not between 1 and 60
       or jsonb_typeof(e->'price') <> 'number'
       or (e->>'price') !~ '^[0-9]{1,8}$' or (e->>'price')::int > 10000000 then
      raise exception 'invalid_variants';
    end if;
  end loop;
  return new;
end $$;

drop trigger if exists products_validate_variants on public.products;
create trigger products_validate_variants before insert or update on public.products
  for each row execute function public.validate_variants();

-- updated_at otomatis
create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at before update on public.products
  for each row execute function public.set_updated_at();

-- Fungsi trigger tidak perlu bisa dipanggil siapa pun lewat API
revoke all on function public.validate_variants() from public, anon, authenticated;
revoke all on function public.set_updated_at()    from public, anon, authenticated;

-- ---------- 3. FUNGSI is_admin ----------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- 4. RLS: HAPUS SEMUA POLICY LAMA, LALU BUAT ULANG ----------
alter table public.products enable row level security;
alter table public.orders   enable row level security;
alter table public.admins   enable row level security;

do $$
declare r record;
begin
  for r in select schemaname, tablename, policyname from pg_policies
           where schemaname = 'public' and tablename in ('products','orders','admins')
  loop
    execute format('drop policy if exists %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
end $$;

-- Cabut semua hak bawaan, beri hanya yang perlu
revoke all on public.products from anon, authenticated;
revoke all on public.orders   from anon, authenticated;
revoke all on public.admins   from anon, authenticated;

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;   -- tetap dibatasi policy is_admin()
grant select on public.orders to authenticated;                      -- tetap dibatasi policy is_admin()
grant update (status) on public.orders to authenticated;             -- admin hanya boleh mengubah status
-- anon TIDAK punya akses langsung ke orders; order dibuat lewat create_order() di bawah.

-- products: publik hanya melihat produk yang tampil; admin melihat & mengubah semuanya
create policy products_select on public.products
  for select to anon, authenticated
  using (is_visible = true or public.is_admin());

create policy products_insert on public.products
  for insert to authenticated with check (public.is_admin());

create policy products_update on public.products
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy products_delete on public.products
  for delete to authenticated using (public.is_admin());

-- orders: hanya admin yang boleh baca dan ubah status
create policy orders_select on public.orders
  for select to authenticated using (public.is_admin());

create policy orders_update on public.orders
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- admins: tanpa policy = tidak bisa diakses lewat API sama sekali.

-- ---------- 5. RPC create_order: harga & total dihitung SERVER, bukan dari browser ----------
create or replace function public.create_order(
  p_name text, p_wa text, p_email text, p_payment text, p_note text, p_items jsonb,
  p_expected_total int default null
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_name  text := btrim(coalesce(p_name, ''));
  v_wa    text := regexp_replace(coalesce(p_wa, ''), '\D', '', 'g');
  v_email text := btrim(coalesce(p_email, ''));
  v_note  text := btrim(coalesce(p_note, ''));
  v_item  jsonb;
  v_prod  public.products%rowtype;
  v_var   jsonb;
  v_qty   int;
  v_price bigint;
  v_sub   bigint;
  v_total bigint := 0;
  v_items jsonb := '[]'::jsonb;
  v_code  text;
  v_recent int;
  v_global int;
begin
  -- nama & catatan: tanpa karakter kontrol (baris baru) dan tanpa tanda < > (cegah pesan WA/HTML palsu)
  if char_length(v_name) < 2 or char_length(v_name) > 80
     or v_name ~ '[[:cntrl:]]' or v_name ~ '[<>]' or v_name ~* 'https?://|www\.' then
    raise exception 'invalid_name'; end if;

  if v_wa like '0%' then v_wa := '62' || substr(v_wa, 2); end if;
  if char_length(v_wa) < 9 or char_length(v_wa) > 15 then
    raise exception 'invalid_wa'; end if;

  if v_email = '' then v_email := '-'; end if;
  if v_email <> '-' and (char_length(v_email) > 120
      or v_email !~ '^[^@\s<>"'']+@[^@\s<>"'']+\.[^@\s<>"'']+$') then
    raise exception 'invalid_email'; end if;

  if p_payment is null or p_payment not in (
      'QRIS (All E-Wallet & M-Banking)','DANA','GoPay','OVO','ShopeePay','Transfer Bank (BCA / SeaBank)') then
    raise exception 'invalid_payment'; end if;

  if char_length(v_note) > 200 or v_note ~ '[[:cntrl:]]' or v_note ~ '[<>]' then raise exception 'invalid_note'; end if;
  if v_note = '' then v_note := '-'; end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'invalid_items'; end if;

  -- Rate limit: per nomor WA (diserialkan dengan advisory lock) + batas global
  perform pg_advisory_xact_lock(hashtext(v_wa));
  select count(*) into v_recent from public.orders
   where buyer_wa = v_wa and created_at > now() - interval '10 minutes';
  if v_recent >= 5 then raise exception 'rate_limited'; end if;
  select count(*) into v_global from public.orders
   where created_at > now() - interval '1 minute';
  if v_global >= 30 then raise exception 'rate_limited'; end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    if coalesce(v_item->>'qty', '') !~ '^[0-9]{1,2}$' then raise exception 'invalid_qty'; end if;
    v_qty := (v_item->>'qty')::int;
    if v_qty < 1 or v_qty > 10 then raise exception 'invalid_qty'; end if;

    select * into v_prod from public.products
     where slug = v_item->>'slug' and is_visible = true and is_ready = true;
    if not found then raise exception 'product_unavailable'; end if;

    select e into v_var from jsonb_array_elements(v_prod.variants) e
     where e->>'id' = v_item->>'variant_id' limit 1;
    if v_var is null then raise exception 'variant_unavailable'; end if;

    if jsonb_typeof(v_var->'price') <> 'number' or (v_var->>'price') !~ '^[0-9]{1,8}$' then
      raise exception 'variant_unavailable'; end if;
    v_price := (v_var->>'price')::bigint;
    v_sub   := v_price * v_qty;
    v_total := v_total + v_sub;

    v_items := v_items || jsonb_build_object(
      'productId', v_prod.slug, 'productName', v_prod.name,
      'variantId', v_var->>'id', 'variantLabel', v_var->>'label',
      'price', v_price::int, 'qty', v_qty, 'subtotal', v_sub::int);
  end loop;

  if v_total > 50000000 then raise exception 'invalid_items'; end if;
  if p_expected_total is not null and p_expected_total <> v_total then
    raise exception 'price_changed'; end if;

  v_code := 'QZA-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));

  insert into public.orders (order_code, buyer_name, buyer_wa, buyer_email,
                             payment_method, note, items, total, status)
  values (v_code, v_name, v_wa, v_email, p_payment, v_note, v_items, v_total::int, 'pending');

  return jsonb_build_object('order_code', v_code, 'total', v_total::int, 'items', v_items);
end $$;

revoke all on function public.create_order(text,text,text,text,text,jsonb,int) from public;
grant execute on function public.create_order(text,text,text,text,text,jsonb,int) to anon, authenticated;

